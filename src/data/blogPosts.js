/**
 * Returns the most recent blog posts sorted by publication date (DD-MM-YYYY) descending.
 */
export const getRecentBlogPosts = (limit = 3) => {
  const parseDate = (dateStr) => {
    const [day, month, year] = dateStr.split('-').map(Number);
    return new Date(year, month - 1, day).getTime();
  };

  return [...BLOG_POSTS]
    .sort((a, b) => parseDate(b.date) - parseDate(a.date) || b.id - a.id)
    .slice(0, limit);
};

/**
 * Finds a blog post by exact slug or normalized slug.
 */
export const getBlogPostBySlug = (slug) => {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim();
  return (
    BLOG_POSTS.find(
      (p) =>
        p.slug === normalized ||
        p.slug.replace(/-\d+$/, '') === normalized ||
        (normalized.includes('antigravity') && p.id === 1)
    ) || null
  );
};

